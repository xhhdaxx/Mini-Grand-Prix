// 预采样：每个赛道生成密集点列，附带切线、法线、累积长度
function buildTrack(def, id) {
  const scale = def.scale || 1;
  const scaleX = def.scaleX || scale;
  const scaleY = def.scaleY || scale;
  const cp = def.controls.map(p => ({ x: p.x * scaleX, y: p.y * scaleY }));
  const n = cp.length;
  const samples = [];
  const STEPS = 32; // 每段采样数
  let cum = 0;
  let prev = null;
  for (let i = 0; i < n; i++) {
    const p0 = cp[(i - 1 + n) % n];
    const p1 = cp[i];
    const p2 = cp[(i + 1) % n];
    const p3 = cp[(i + 2) % n];
    for (let s = 0; s < STEPS; s++) {
      const t = s / STEPS;
      const pt = catmullRom(p0, p1, p2, p3, t);
      if (prev) cum += Math.hypot(pt.x - prev.x, pt.y - prev.y);
      // 切线（用前后采样差）
      const tNext = (s + 1) / STEPS;
      const ptNext = catmullRom(p0, p1, p2, p3, tNext);
      let tx = ptNext.x - pt.x, ty = ptNext.y - pt.y;
      const tl = Math.hypot(tx, ty) || 1;
      tx /= tl; ty /= tl;
      // 法线（右侧为正）
      const nx = -ty, ny = tx;
      samples.push({
        x: pt.x, y: pt.y,
        tx, ty, nx, ny,
        s: cum,
        // 弯道强度（用二阶差分近似）：相邻切线夹角变化
        curve: 0,
        roadScale: 1
      });
      prev = pt;
    }
  }
  // 闭合：累积长度补到首尾衔接
  const first = samples[0], last = samples[samples.length - 1];
  cum += Math.hypot(first.x - last.x, first.y - last.y);
  const totalLength = cum;

  // 计算每个采样的曲率（前后切线夹角）
  const m = samples.length;
  for (let i = 0; i < m; i++) {
    const a = samples[(i - 2 + m) % m];
    const b = samples[(i + 2) % m];
    const cross = a.tx * b.ty - a.ty * b.tx;
    const dot = a.tx * b.tx + a.ty * b.ty;
    samples[i].curve = Math.atan2(Math.abs(cross), dot);
  }

  return {
    id,
    name: def.name,
    laps: def.laps,
    raceDistanceMeters: def.raceDistanceMeters || totalLength,
    // 只放大赛道的占地与长度，不放大路宽，否则相邻弯道会再次叠在一起。
    halfWidth: def.width,
    curbWidth: 8,
    // 每一侧缓冲区为完整赛道宽度的 1/3，空气墙位于缓冲区最外沿。
    bufferWidth: def.bufferWidth || def.width * 2 / 3,
    worldScale: Math.max(scaleX, scaleY),
    worldScaleX: scaleX,
    worldScaleY: scaleY,
    // 四条赛道均使用独立维修区道路，由各自道路外侧空气墙限制。
    hasDedicatedPitLane: true,
    controls: cp,
    samples,
    totalLength,
    overpassRange: Array.isArray(def.overpassControlRange)
      ? def.overpassControlRange.map(controlIndex => controlIndex * STEPS)
      : null,
    landmarks: Array.isArray(def.landmarks)
      ? def.landmarks.map(item => ({ ...item, x:item.x * scaleX, y:item.y * scaleY }))
      : []
  };
}

const _cache = {};
export function getTrack(id) {
  if (!_cache[id]) _cache[id] = buildTrack(TRACKS[id], id);
  return _cache[id];
}

