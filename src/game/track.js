// 给定玩家世界坐标，找到最近赛道采样点索引与横向偏移
export function nearestSample(track, x, y) {
  let best = 0, bestD = Infinity;
  const s = track.samples;
  for (let i = 0; i < s.length; i++) {
    const d = (s[i].x - x) * (s[i].x - x) + (s[i].y - y) * (s[i].y - y);
    if (d < bestD) { bestD = d; best = i; }
  }
  const samp = s[best];
  const dx = x - samp.x, dy = y - samp.y;
  const lateral = dx * samp.nx + dy * samp.ny;
  return { idx: best, lateral, dist: Math.sqrt(bestD), roadHalfWidth: track.halfWidth * (samp.roadScale || 1), bufferWidth: track.bufferWidth * (samp.roadScale || 1) };
}

// 带位置提示的最近点查询：车辆每帧位移很小，先在 hintIdx 附近窗口内搜，
// 命中即返回；窗口内最近点距离过大（跨段穿越/重生）时回退到全量扫描。
// hintIdx 为空或越界时等同 nearestSample。
export function nearestSampleHinted(track, x, y, hintIdx, window = 24) {
  const s = track.samples;
  const m = s.length;
  if (!Number.isInteger(hintIdx) || hintIdx < 0 || hintIdx >= m) {
    return nearestSample(track, x, y);
  }
  let best = hintIdx, bestD = Infinity;
  for (let off = -window; off <= window; off++) {
    const i = ((hintIdx + off) % m + m) % m;
    const d = (s[i].x - x) * (s[i].x - x) + (s[i].y - y) * (s[i].y - y);
    if (d < bestD) { bestD = d; best = i; }
  }
  // 窗口内最近点若仍很远，可能车被传送到别处，回退全量。
  if (bestD > 400 * 400) return nearestSample(track, x, y);
  const samp = s[best];
  const dx = x - samp.x, dy = y - samp.y;
  const lateral = dx * samp.nx + dy * samp.ny;
  return { idx: best, lateral, dist: Math.sqrt(bestD), roadHalfWidth: track.halfWidth * (samp.roadScale || 1), bufferWidth: track.bufferWidth * (samp.roadScale || 1) };
}

export function getRunoffSurface(track, sampleIndex, lateral) {
  const zone = Math.floor(sampleIndex / 44);
  const side = lateral < 0 ? -1 : 1;
  const hash = Math.abs((zone * 73 + side * 41 + track.name.length * 29) % 100);
  return hash < 52 ? 'gravel' : 'runoff';
}

