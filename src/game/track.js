// PIT IN 的合法跨线区域；上海维修区位于主赛道右侧（正 lateral）。
// 两端各留少量采样余量，避免一帧位移跨过边界时被误判为赛道越界。
export function isPitEntryTransition(track, trackIndex, lateral) {
  if (!track || !['sunshine', 'rainbow', 'galaxy', 'yasmarina', 'lasvegas', 'baku', 'jeddah', 'australia', 'silverstone', 'hockenheim', 'bahrain', 'brazil', 'miami', 'canada', 'spain', 'hungary', 'austria', 'netherlands', 'singapore', 'austin', 'malaysia', 'mexico', 'qatar', 'italy'].includes(track.id) || !Number.isFinite(trackIndex) || !Number.isFinite(lateral)) return false;
  const cfg = getPitConfig(track), m = track.samples.length;
  let k = ((trackIndex % m) + m) % m;
  if (k > m / 2) k -= m;
  const correctSide = ['baku', 'jeddah', 'silverstone', 'brazil', 'miami', 'canada', 'qatar'].includes(track.id) ? lateral < -track.halfWidth * 0.45 : lateral > track.halfWidth * 0.45;
  return k >= cfg.entryGateStart - 8 && k <= cfg.entryGateEnd + 8 && correctSide;
}

